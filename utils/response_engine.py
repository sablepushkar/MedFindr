from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

from utils.drug_lookup import search_drug
from utils.ebm_risk import EBMExplanation, assess_risk_ebm
from utils.urgency import UrgencyResult, assess_urgency


@dataclass
class Section:
    title: str
    content: str
    level: Optional[str] = None
    items: List[str] = field(default_factory=list)


@dataclass
class StructuredResponse:
    concern: str
    urgency: UrgencyResult
    ebm: Optional[EBMExplanation] = None
    sections: List[Section] = field(default_factory=list)
    drug_result: Optional[Dict[str, Any]] = None
    notes: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "concern": self.concern,
            "urgency": self.urgency.to_dict(),
            "ebm": self.ebm.to_dict() if self.ebm else None,
            "sections": [
                {
                    "title": s.title,
                    "content": s.content,
                    "level": s.level,
                    "items": s.items,
                }
                for s in self.sections
            ],
            "drug_result": self.drug_result,
            "notes": self.notes,
        }


def build_response(
    concern: str,
    drug_name: Optional[str] = None,
    include_ebm: bool = True,
) -> StructuredResponse:
    cleaned = (concern or "").strip()

    urgency = assess_urgency(cleaned)

    ebm_result = None
    if include_ebm:
        ebm_result = assess_risk_ebm(cleaned, urgency_level=urgency.level)

    sections: List[Section] = []

    sections.append(
        Section(
            title="1. Understanding the Concern",
            content=cleaned if cleaned else "No concern text provided.",
        )
    )

    sections.append(
        Section(
            title="2. Urgency Assessment (Rule-based)",
            content=urgency.recommendation,
            level=urgency.level,
            items=list(urgency.reasons),
        )
    )

    if ebm_result:
        factor_items = ebm_result.top_factors[:]
        for k, v in ebm_result.local_contribution.items():
            factor_items.append(f"{k}: {v:.2f}")

        sections.append(
            Section(
                title="3. Explainable Risk Assessment (EBM)",
                content=ebm_result.summary,
                level=ebm_result.risk_level,
                items=factor_items,
            )
        )

    if urgency.level == "high":
        next_content = "High urgency signals detected. Urgent medical evaluation should be prioritised."
    elif urgency.level == "moderate":
        next_content = "Moderate concern indicators present. Close monitoring and timely medical review are recommended."
    else:
        next_content = "No strong red-flag patterns detected. General self-care measures may be appropriate while monitoring."

    sections.append(
        Section(
            title="4. Possible Next Steps / Remedies (general)",
            content=next_content,
            items=[
                "Rest and maintain good hydration",
                "Monitor symptoms over the next 24–48 hours",
                "For mild symptoms, consider seeking pharmacy advice on suitable over-the-counter options",
                "Seek medical attention if symptoms persist, worsen, or new concerning signs appear",
            ],
        )
    )

    drug_result = None
    if drug_name and drug_name.strip():
        drug_result = search_drug(drug_name.strip())

    notes = (
        f"Response generated by MedFindr {__import__('config').APP_VERSION}. "
        "Urgency assessment is rule-based and fully transparent. "
        "EBM component currently uses a structured placeholder that matches the "
        "output format of a real InterpretML model. A trained model can be added without changing the pipeline."
    )

    return StructuredResponse(
        concern=cleaned,
        urgency=urgency,
        ebm=ebm_result,
        sections=sections,
        drug_result=drug_result,
        notes=notes,
    )
